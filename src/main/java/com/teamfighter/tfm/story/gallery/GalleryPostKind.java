package com.teamfighter.tfm.story.gallery;

/**
 * 게시글 유형 열 가지. 레퍼런스 모드의 [게시글 유형 다양성 규칙] 을 그대로 옮겼다.
 *
 * <h2>유형이 왜 데이터인가</h2>
 *
 * 프롬프트에 "다양하게 써라" 라고만 적으면 모델은 <b>같은 각도로 스무 개</b>를 쓴다.
 * 앞 세션이 세트 나열을 프롬프트로 세 번 조이고도 못 고친 것과 같은 실패다 —
 * 지시로 막을 수 없는 것은 <b>구조로</b> 막아야 한다.
 *
 * <p>그래서 유형을 값으로 두고, 한 호출에 "이 유형 몇 개" 를 숫자로 박아 넣는다.
 * 그러면 나열이 아니라 <b>배분</b>이 된다. 저장할 때도 유형이 남으므로 실제로
 * 배분대로 나왔는지 나중에 셀 수 있다.
 *
 * @see GalleryChunk 유형을 묶어 호출 단위로 나눈다 (D72)
 */
public enum GalleryPostKind {

    SKIT("상황극/드립", """
            선수들의 가상 대화나 속마음을 대본 형식으로 재구성하고 마지막에 한 줄 촌평.
            (예: "???: 야 너 왜 지고 POG 받아?" / "존나 애처롭다 ㅋㅋㅋㅋ")"""),

    BAIT("어그로 제목", """
            "~.txt" / "~한 진짜 이유" 꼴의 제목으로 낚고, 본문에서 뇌피셜 서사를
            그럴듯하게 풀어라. 제목이 본문보다 세야 한다"""),

    ANALYSIS("분석글", """
            "★ 현 폼 최고 선수 TOP5 ★" 같은 분석노트 스타일. 아래 사실 블록의 실제
            수치를 근거로 순위를 매기고 팩트만 나열하듯 써라. 닉네임은 "분석노트",
            "프로토스" 같은 고정닉 느낌. 마지막에 "개추 눌러라 냄글 가게 ㅋㅋㅋ"."""),

    LIVE("실황/직관", """
            경기 보면서 실시간으로 갈긴 듯한 글. 특정 세트의 특정 장면을 중계하듯
            묘사하라. "방금 그 한타 뭐냐 ㅅㅂ", 직관러의 현장 분위기"""),

    FLAME("키배 떡밥", """
            억까 vs 억빠가 정면충돌할 주제를 던져라 (POG 선정 논란, 감독 밴픽 책임론,
            에이스 의존도). <b>이 글의 댓글에는 반드시 실제 키배가 폭발해야 한다</b>"""),

    SAGA("서사글", """
            라이벌·대회·과거 전적에 얽힌 글. 아래 맥락 태그가 있으면 그것을 물고 늘어져라.
            배경이 없으면 팀 간 상성 떡밥으로 대체"""),

    PLAYER("선수 저격/찬양", """
            특정 선수의 스탯을 콕 집어 극단적 저격 또는 극단적 찬양.
            (예: "0/0/0 ㅋㅋㅋ 그냥 맵에 가구 하나 세워둔 거랑 뭐가 다름?")"""),

    DAILY("갤 일상", """
            유저 일상과 경기가 섞인 잡담. ("내일 출근인데 싱글벙글 웃다가 잠 다 깸 ㄹㅇ")
            <b>잡담글에 경기 분석을 억지로 우겨넣지 마라.</b> 잡담엔 잡담으로 답한다"""),

    TRANSFER("이적시장", """
            선수 이동 떡밥. 저연봉인데 하드캐리한 선수는 "이 가격에 이 폼? 뺏기기 전에 잡아라",
            부진하면 "방출 각". <b>연봉 수치는 우리가 안 준다 — 없는 숫자를 인용하지 말고
            스탯만 근거로 삼아라</b>"""),

    SCRAP("기록 스크랩", """
            아래 선수 성적 표나 맥락(순위·연패·라이벌)을 <b>그대로 퍼와서</b> 반응하는 글.
            본문 첫 줄에 "[기록 스크랩]" 을 붙이고 인용한 수치를 적은 뒤, 한 줄 띄우고
            본인 의견을 붙여라. 방향은 넷 중 하나: (a) 토론 유도 "이거 어케 생각함?"
            (b) 반박/저격 (c) 옹호/지지 (d) 확대해석 "이거 사실 ~때문 아니냐?".
            <b>표에 없는 수치를 지어내면 이 유형은 통째로 실패다</b> — 인용이 전부인 글이다""");

    private final String label;
    private final String guidance;

    GalleryPostKind(String label, String guidance) {
        this.label = label;
        this.guidance = guidance;
    }

    /** 화면에 그리는 한글 이름. */
    public String label() {
        return label;
    }

    /** 프롬프트에 넣는 지시. */
    public String guidance() {
        return guidance;
    }

    /**
     * 모델이 준 유형 문자열을 값으로 바꾼다.
     *
     * @return 모르는 값이면 {@code null}. <b>예외가 아니다</b> — 유형 하나를 못 읽었다고
     *         글 스무 개를 버리는 것은 손해가 크다. 부르는 쪽이 그 조각의 기본 유형으로 채운다
     */
    public static GalleryPostKind parse(String raw) {
        if (raw == null || raw.isBlank()) {
            return null;
        }
        String normalized = raw.strip().toUpperCase(java.util.Locale.ROOT);
        for (GalleryPostKind kind : values()) {
            if (kind.name().equals(normalized)) {
                return kind;
            }
        }
        return null;
    }
}
