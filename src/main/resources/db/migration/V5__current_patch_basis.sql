-- 기준을 "현재 패치 · 현재 커리어" 로 옮긴다 (2026-08-28, decision.md D53)
--
-- 유저는 현재 패치 기준으로 플레이한다. 앱이 "A 가 좋다" 고 하면 그건 지금 좋다는
-- 뜻이어야 하는데, 지금 구현은 (1) 감쇠가 사실상 꺼져 있어 옛 패치를 그대로 합치고
-- (2) GLOBAL 스코프가 서로 다른 밸런스의 커리어를 한 줄로 합친다.
--
-- 두 가지를 바꾼다.

SET client_encoding = 'UTF8';


-- (1) 메타 감쇠 반감기 12 → 2
--
-- 12 는 실측상 아무 일도 하지 않았다. 한 커리어의 경기가 걸친 패치 폭이 1~3 뿐이라
-- 최소 가중치가 0.841 이고, 티어 추정이 평균 0.23%p 움직인다.
--
-- 2 로 줄여도 비용이 거의 없다. 유효표본이 표본 기준선(10)을 넘는 챔피언 수가
-- 37명에서 37명 그대로다 — 챔피언당 출전이 20~180건이라 감쇠 후에도 기준선을 넘는다.
-- 대신 티어 순위가 최대 9칸 움직인다.
--
-- 자기 변경 축(2)은 그대로 둔다. 한 챔피언이 하향되면 그에게 카운터당하던 챔피언의
-- 승률도 따라 움직이므로(나비효과), 바뀐 챔피언만 깎는 것으로는 부족하다.
-- 메타 축이 모든 챔피언에게 똑같이 걸려 그것을 담는다.
--
-- 이 값은 언제든 UPDATE 한 줄로 바꿔 재집계할 수 있다. 실측 패치 밀도가 시즌당
-- 3.8개이므로 2 는 약 0.5시즌, 4 는 약 1시즌이다.
UPDATE analysis_config
   SET value = 2,
       note = '메타 변화 감쇠 반감기(경과 패치 수). 실측 패치 밀도 시즌당 3.8개이므로 2패치는 약 0.5시즌이다. 12 는 경기가 걸친 패치 폭(1~3)보다 훨씬 커서 아무 일도 하지 않았다 (D53)',
       updated_at = now()
 WHERE key = 'meta_decay_half_life';


-- (2) GLOBAL 스코프의 집계 결과를 지운다
--
-- 패치는 커리어마다 고유 생성된다. 19패치를 거치면 같은 이름의 챔피언이라도 커리어별로
-- 스탯이 반대 방향으로 가 있다 — 실측 예: Dancer 가 한 커리어에서 max_hp +1224,
-- 다른 커리어에서 -292 다. GLOBAL 은 그것을 한 줄로 합친다. 표본은 3배지만
-- 합쳐진 대상이 같은 챔피언이 아니다.
--
-- 스키마의 agg_scope ENUM 과 GLOBAL 을 허용하는 유일키는 그대로 둔다. 커리어별 밸런스를
-- 정규화할 방법을 찾으면 되살릴 자리다. 지금은 쓰지 않으므로 낡은 행만 지운다.
DELETE FROM champion_matchup    WHERE scope = 'GLOBAL';
DELETE FROM champion_performance WHERE scope = 'GLOBAL';

COMMENT ON TYPE agg_scope IS
  'GLOBAL 은 현재 쓰지 않는다 — 커리어마다 패치 역사가 달라 챔피언 강도를 합칠 수 없다 (D53). CAREER 만 생산한다.';
