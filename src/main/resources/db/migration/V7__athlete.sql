  '선수. 값은 전부 마지막 적재 시점의 스냅샷이고 이력이 없다 — 과거 경기 시점의 나이·연봉이 아니다 (D58)';
COMMENT ON COLUMN athlete.category IS
  '선수의 주특기. Athlete.Category 는 ChampionCategory 타입이지만 챔피언 분류가 아니다 (savefile.md)';
