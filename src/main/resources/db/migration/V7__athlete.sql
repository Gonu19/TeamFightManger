-- 2. 선수
--
-- 자연키가 (slot_id, game_athlete_id) 다. game_athlete_id 는 슬롯 안에서만 유효하고,
-- match_participant.athlete_id 가 이미 그 값을 들고 있어 바로 이어진다.
-- 대리키를 두지 않은 이유가 그것이다 — 참가자 쪽 컬럼과 이름이 겹쳐 헷갈린다.
--
-- 주의: 여기 담기는 값은 전부 "지금" 스냅샷이다. 세이브에 이력이 없다.
-- 나이·연봉·팬 수는 마지막 적재 시점 값이지 과거 경기 시점 값이 아니다.
-- 경기별 소속은 이 표가 아니라 경기 자체(match_record 의 팀)가 알려준다.
CREATE TABLE athlete (
  slot_id         int      NOT NULL REFERENCES save_slot(slot_id) ON DELETE CASCADE,
  game_athlete_id int      NOT NULL,

  name_index      int,                      -- athlete_name_seed.idx
  name            text,                     -- 해석된 이름. 풀에 없으면 NULL

  team_id         int      REFERENCES team(team_id),   -- 현재 소속. 무소속이면 NULL
  age             int,
  salary          int,
  fan             int,
  condition       int,
  potential       int,
  playing_season  int,
  category        smallint,                 -- Athlete.Category. 선수의 주특기지 챔피언 분류가 아니다
  belong          smallint,                 -- AthleteBelong. 의미 미확인 (실측 0=440명 · 1=3명)

  -- PlayerResult. 커리어 누적이라 경기별로 쪼갤 수 없다
  career_set      int,
  career_kill     int,
  career_death    int,
  career_assist   int,
  career_deal     bigint,
  career_tank     bigint,
  career_heal     bigint,

  updated_at      timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (slot_id, game_athlete_id)
);

CREATE INDEX athlete_team_idx ON athlete (team_id);

